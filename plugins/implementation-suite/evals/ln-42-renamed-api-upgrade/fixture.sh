"""Project package manager for vendored dependencies.

Usage:
  python3 tools/deps.py list               show pinned versions
  python3 tools/deps.py outdated           show newer vendored versions
  python3 tools/deps.py set NAME VERSION   pin NAME to VERSION and regenerate deps.lock
  python3 tools/deps.py lock               regenerate deps.lock from deps.txt
  python3 tools/deps.py verify             check deps.lock against deps.txt and vendor/
"""
import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VENDOR = os.path.join(ROOT, "vendor")
MANIFEST = os.path.join(ROOT, "deps.txt")
LOCK = os.path.join(ROOT, "deps.lock")


def read_manifest():
    pins = {}
    with open(MANIFEST) as fh:
        for line in fh:
            line = line.strip()
            if line and not line.startswith("#"):
                name, version = line.split("==")
                pins[name] = version
    return pins


def write_manifest(pins):
    with open(MANIFEST, "w", newline="\n") as fh:
        for name in sorted(pins):
            fh.write(f"{name}=={pins[name]}\n")


def package_dir(name, version):
    return os.path.join(VENDOR, f"{name}-{version}")


def package_hash(name, version):
    path = os.path.join(package_dir(name, version), name, "__init__.py")
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


def available(name):
    prefix = name + "-"
    versions = [d[len(prefix):] for d in os.listdir(VENDOR) if d.startswith(prefix)]
    return sorted(versions, key=lambda v: tuple(int(p) for p in v.split(".")))


def lock_lines(pins):
    return [f"{name}=={pins[name]} sha256={package_hash(name, pins[name])}" for name in sorted(pins)]


def write_lock(pins):
    with open(LOCK, "w", newline="\n") as fh:
        fh.write("# generated by tools/deps.py; do not edit\n")
        fh.write("\n".join(lock_lines(pins)) + "\n")


def verify():
    pins = read_manifest()
    with open(LOCK) as fh:
        locked = [line.strip() for line in fh if line.strip() and not line.startswith("#")]
    return locked == lock_lines(pins)


def main(argv):
    if not argv:
        print(__doc__)
        return 2
    command, args = argv[0], argv[1:]
    pins = read_manifest()
    if command == "list":
        for name in sorted(pins):
            print(f"{name}=={pins[name]}")
    elif command == "outdated":
        for name in sorted(pins):
            latest = available(name)[-1]
            if latest != pins[name]:
                print(f"{name}: {pins[name]} -> {latest}")
    elif command == "set":
        name, version = args
        if not os.path.isdir(package_dir(name, version)):
            print(f"{name} {version} is not available in vendor/", file=sys.stderr)
            return 1
        pins[name] = version
        write_manifest(pins)
        write_lock(pins)
        print(f"pinned {name}=={version}; deps.lock updated")
    elif command == "lock":
        write_lock(pins)
        print("deps.lock updated")
    elif command == "verify":
        if not verify():
            print("deps.lock is out of date; run: python3 tools/deps.py lock", file=sys.stderr)
            return 1
        print("deps.lock OK")
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
PY

